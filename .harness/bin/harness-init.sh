#!/bin/sh

set -e

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
. "$SCRIPT_DIR/harness-common.sh"

PROJECT_ROOT="$(pwd)"
LANG="zh"
REFRESH="no"
GENERATE_REPO_MAP="yes"

for arg in "$@"; do
  case "$arg" in
    --project-root=*)
      PROJECT_ROOT="${arg#--project-root=}"
      ;;
    --lang=*)
      LANG="${arg#--lang=}"
      ;;
    --refresh)
      REFRESH="yes"
      ;;
    --skip-repo-map)
      GENERATE_REPO_MAP="no"
      ;;
    --help|-h)
      echo "Usage: sh harness-init.sh [--project-root=PATH] [--lang=zh|en] [--refresh] [--skip-repo-map]"
      exit 0
      ;;
    *)
      echo "Unknown option: $arg" >&2
      exit 1
      ;;
  esac
done

PROJECT_ROOT="$(cd "$PROJECT_ROOT" && pwd)"
PROJECT_NAME="$(harness_project_name "$PROJECT_ROOT")"
BACKEND="$(harness_detect_backend "$PROJECT_ROOT")"
FRONTEND="$(harness_detect_frontend "$PROJECT_ROOT")"
DATABASE="$(harness_detect_database "$PROJECT_ROOT")"
BUILD_TOOL="$(harness_detect_build "$PROJECT_ROOT")"
ARCH_STYLE="$(harness_detect_architecture "$PROJECT_ROOT")"
MODULES_JSON="$(harness_detect_modules "$PROJECT_ROOT")"
TIMESTAMP="$(harness_now_iso)"
COMMIT_HASH="$(harness_git_commit "$PROJECT_ROOT")"

HARNESS_DIR="$PROJECT_ROOT/.harness"
BIN_DIR="$HARNESS_DIR/bin"
HOOK_DIR="$HARNESS_DIR/git-hooks"
ARCH_DIR="$HARNESS_DIR/architecture"
RULES_DIR="$HARNESS_DIR/rules"
STATE_DIR="$HARNESS_DIR/state"
OVERRIDE_DIR="$HARNESS_DIR/overrides"
CACHE_DIR="$PROJECT_ROOT/.cache"
SHARED_DIR="$CACHE_DIR/shared"

mkdir -p "$BIN_DIR" "$HOOK_DIR" "$ARCH_DIR" "$RULES_DIR" "$STATE_DIR" "$OVERRIDE_DIR" "$SHARED_DIR"

copy_if_needed() {
  SRC="$1"
  DEST="$2"

  if [ "$SRC" != "$DEST" ]; then
    cp "$SRC" "$DEST"
  fi
  chmod +x "$DEST" 2>/dev/null || true
}

copy_if_needed "$SCRIPT_DIR/harness-common.sh" "$BIN_DIR/harness-common.sh"
copy_if_needed "$SCRIPT_DIR/harness-init.sh" "$BIN_DIR/harness-init.sh"
copy_if_needed "$SCRIPT_DIR/harness-check.sh" "$BIN_DIR/harness-check.sh"
copy_if_needed "$SCRIPT_DIR/harness-fix.sh" "$BIN_DIR/harness-fix.sh"
copy_if_needed "$SCRIPT_DIR/harness-gate.sh" "$BIN_DIR/harness-gate.sh"
copy_if_needed "$SCRIPT_DIR/harness-worktree.sh" "$BIN_DIR/harness-worktree.sh"
copy_if_needed "$SCRIPT_DIR/harness-checkpoint.sh" "$BIN_DIR/harness-checkpoint.sh"
copy_if_needed "$SCRIPT_DIR/harness-repo-map.sh" "$BIN_DIR/harness-repo-map.sh"
copy_if_needed "$SCRIPT_DIR/harness-repo-index.sh" "$BIN_DIR/harness-repo-index.sh"
copy_if_needed "$SCRIPT_DIR/harness-selfcheck.sh" "$BIN_DIR/harness-selfcheck.sh"

copy_if_needed "$(cd "$SCRIPT_DIR/../git-hooks" && pwd)/pre-commit" "$HOOK_DIR/pre-commit"
copy_if_needed "$(cd "$SCRIPT_DIR/../git-hooks" && pwd)/pre-push" "$HOOK_DIR/pre-push"
copy_if_needed "$(cd "$SCRIPT_DIR/../git-hooks" && pwd)/commit-msg" "$HOOK_DIR/commit-msg"

cat > "$PROJECT_ROOT/PROJECT_CONFIG.md" <<EOF
# 项目配置

> Generated by Scrum Skills Harness. 用于初始化项目级约束与 Agent 上下文。

## 项目信息
- 项目名称：$PROJECT_NAME
- 项目路径：$PROJECT_ROOT
- 项目类型：$( [ "$FRONTEND" != "unknown" ] && [ "$BACKEND" != "unknown" ] && echo "前后端混合项目" || echo "通用代码仓库" )
- 初始化时间：$TIMESTAMP

## 技术栈
- 后端：$BACKEND
- 前端：$FRONTEND
- 数据库：$DATABASE
- 构建工具：$BUILD_TOOL

## 架构模式
- 架构风格：$ARCH_STYLE
- Harness 目录：.harness/
- Git Hooks：core.hooksPath = .harness/git-hooks

## 代码约束
- 文件大小：<= 800 行
- 方法大小：<= 50 行
- 前端视图层禁止直接 import axios
- 前端禁止直接读取 API Key / Token / Secret 类环境变量
- Java application 层禁止直接 import infrastructure 包
- 禁止提交 *_Refactored.* 临时文件
EOF

cat > "$CACHE_DIR/.project-info.json" <<EOF
{
  "project_name": "$(harness_json_escape "$PROJECT_NAME")",
  "project_root": "$(harness_json_escape "$PROJECT_ROOT")",
  "initialized": true,
  "initialized_at": "$TIMESTAMP",
  "last_used": "$TIMESTAMP",
  "config_version": "2.0",
  "cache_version": "2.0",
  "architecture_style": "$ARCH_STYLE",
  "tech_stack": {
    "backend": "$(harness_json_escape "$BACKEND")",
    "frontend": "$(harness_json_escape "$FRONTEND")",
    "database": "$(harness_json_escape "$DATABASE")",
    "build_tool": "$(harness_json_escape "$BUILD_TOOL")"
  },
  "modules": $MODULES_JSON
}
EOF

cat > "$HARNESS_DIR/README.md" <<EOF
# Harness Directory

本目录是项目级 Harness 合同与 Git 门禁的事实源。

## 目录说明

- \`project-profile.json\`：项目画像
- \`architecture/\`：架构合同与依赖方向
- \`rules/\`：后端、前端、测试规则
- \`git-hooks/\`：版本化 Git hooks
- \`bin/\`：仓库内可执行 harness 脚本
- \`state/\`：漂移基线与最近检查结果
- \`overrides/\`：审计型豁免，不再允许 \`[skip-review]\`
- \`.worktrees/\`：按任务隔离的 Git worktree 工作区（运行时目录，不提交）
- \`.cache/shared/repo-map.md\`：人类可读仓库地图
- \`.cache/shared/repo-index.json\`：结构化仓库索引

## 使用方式

- 初始化：\`sh .harness/bin/harness-init.sh --project-root=.\`
- 增量检查：\`sh .harness/bin/harness-check.sh --changed-files\`
- 新任务隔离：\`sh .harness/bin/harness-worktree.sh create TASK-ID\`
- 检查点提交：\`sh .harness/bin/harness-checkpoint.sh "checkpoint note"\`
- 刷新 repo-map：\`sh .harness/bin/harness-repo-map.sh --project-root=.\`
- 刷新 repo-index：\`sh .harness/bin/harness-repo-index.sh --project-root=.\`
- 提交前检查：由 \`.harness/git-hooks/pre-commit\` 自动触发
- 推送前检查：由 \`.harness/git-hooks/pre-push\` 自动触发
EOF

cat > "$HARNESS_DIR/project-profile.json" <<EOF
{
  "schema_version": "2.0",
  "generated_at": "$TIMESTAMP",
  "generated_from_commit": "$COMMIT_HASH",
  "project": {
    "name": "$(harness_json_escape "$PROJECT_NAME")",
    "root": "."
  },
  "architecture": {
    "style": "$ARCH_STYLE",
    "repository_as_system_of_record": true
  },
  "git": {
    "hooks_path": ".harness/git-hooks",
    "protected_branches": ["main", "master"],
    "require_review_prefix": true
  },
  "stack": {
    "backend": "$(harness_json_escape "$BACKEND")",
    "frontend": "$(harness_json_escape "$FRONTEND")",
    "database": "$(harness_json_escape "$DATABASE")",
    "build_tool": "$(harness_json_escape "$BUILD_TOOL")"
  },
  "modules": $MODULES_JSON
}
EOF

cat > "$ARCH_DIR/contract.yaml" <<EOF
version: 2
project:
  name: $PROJECT_NAME
  root: .
architecture:
  style: $ARCH_STYLE
  repository_as_system_of_record: true
backpressure:
  require_review_prefix: true
  require_versioned_hooks: true
  max_file_lines: 800
  max_method_lines: 50
rules:
  - id: git-hooks-path
    severity: error
    auto_fixable: true
  - id: no-refactored-suffix
    severity: error
    auto_fixable: false
  - id: frontend-no-direct-axios
    severity: error
    auto_fixable: false
  - id: frontend-no-secret-env
    severity: error
    auto_fixable: false
  - id: application-no-infrastructure-import
    severity: error
    auto_fixable: false
EOF

cat > "$ARCH_DIR/dependency-rules.yaml" <<EOF
version: 2
rules:
  - id: application-no-infrastructure-import
    when:
      path_contains: /application/
      file_extension: .java
    deny:
      regex: '^import .*\\.infrastructure\\.'
    message: Java application 层不得直接依赖 infrastructure 包
  - id: frontend-no-direct-axios
    when:
      path_prefix_any:
        - src/views/
        - src/components/
        - src/pages/
        - web/src/views/
        - web/src/components/
        - web/src/pages/
    deny:
      regex: 'import\\s+axios\\s+from'
    message: 前端视图层不得直接 import axios，必须通过 api/composable/service 边界
EOF

cat > "$RULES_DIR/backend.yaml" <<EOF
version: 2
rules:
  - id: application-no-infrastructure-import
    severity: error
  - id: file-size-limit
    severity: error
    max_lines: 800
  - id: no-refactored-suffix
    severity: error
EOF

cat > "$RULES_DIR/frontend.yaml" <<EOF
version: 2
rules:
  - id: frontend-no-direct-axios
    severity: error
  - id: frontend-no-secret-env
    severity: error
  - id: file-size-limit
    severity: error
    max_lines: 800
EOF

cat > "$RULES_DIR/tests.yaml" <<EOF
version: 2
rules:
  - id: changed-code-requires-check
    severity: error
    message: 代码改动必须经过 harness-check 与 Git hooks
EOF

cat > "$STATE_DIR/drift-baseline.json" <<EOF
{
  "generated_at": "$TIMESTAMP",
  "generated_from_commit": "$COMMIT_HASH",
  "approved_open_violations": []
}
EOF

cat > "$OVERRIDE_DIR/README.md" <<EOF
# Harness Overrides

不再允许 \`[skip-review]\`。

如需临时豁免，必须：

1. 在本目录创建 \`ADR-xxx.yaml\`
2. 提供 \`reason\`、\`scope\`、\`owner\`、\`expires_at\`、\`approved_by\`
3. 在 commit message 中写入 \`[imperial-override:ADR-xxx]\`
EOF

if [ -d "$PROJECT_ROOT/.git" ]; then
  (
    cd "$PROJECT_ROOT"
    git config core.hooksPath .harness/git-hooks
  )
fi

chmod +x "$BIN_DIR"/*.sh "$HOOK_DIR"/* 2>/dev/null || true

if [ -f "$BIN_DIR/harness-repo-index.sh" ]; then
  sh "$BIN_DIR/harness-repo-index.sh" --project-root="$PROJECT_ROOT" >/dev/null
fi

if [ "$GENERATE_REPO_MAP" = "yes" ] && [ -f "$BIN_DIR/harness-repo-map.sh" ]; then
  sh "$BIN_DIR/harness-repo-map.sh" --project-root="$PROJECT_ROOT" >/dev/null
fi

if [ -f "$BIN_DIR/harness-check.sh" ]; then
  sh "$BIN_DIR/harness-check.sh" --project-root="$PROJECT_ROOT" --all >/dev/null 2>&1 || true
  BASELINE_ENTRIES=$(grep -oE '"rule_id":"[^"]+","path":"[^"]+"' "$STATE_DIR/last-report.json" 2>/dev/null | \
    sed 's/"rule_id":"\([^"]*\)","path":"\([^"]*\)"/    {"rule_id":"\1","path":"\2"}/' | \
    sort -u | \
    awk 'BEGIN { first = 1 } NF { if (first) { printf "%s", $0; first = 0 } else { printf ",\n%s", $0 } }')

  cat > "$STATE_DIR/drift-baseline.json" <<EOF
{
  "generated_at": "$TIMESTAMP",
  "generated_from_commit": "$COMMIT_HASH",
  "approved_open_violations": [
$BASELINE_ENTRIES
  ]
}
EOF
fi

if [ "$LANG" = "en" ]; then
  echo "Harness initialized for $PROJECT_NAME"
  echo "  project root : $PROJECT_ROOT"
  echo "  hooks path   : .harness/git-hooks"
  echo "  architecture : $ARCH_STYLE"
else
  echo "已为 $PROJECT_NAME 初始化 Harness"
  echo "  项目根目录 : $PROJECT_ROOT"
  echo "  hooks 路径  : .harness/git-hooks"
  echo "  架构风格    : $ARCH_STYLE"
fi

if [ "$REFRESH" = "yes" ]; then
  exit 0
fi
